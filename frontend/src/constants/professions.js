export const getProfessionById = (idOrValue) => {
  if (!idOrValue) return PROFESSIONS[0];
  const query = String(idOrValue).toLowerCase();
  return (
    PROFESSIONS.find((p) => p.id === query || p.value.toLowerCase() === query) ||
    PROFESSIONS[0]
  );
};
